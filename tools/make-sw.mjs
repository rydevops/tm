// Generates sw.js: an offline precache of every shipped file, versioned by a content hash. Run after any change: node tools/make-sw.mjs
import fs from 'fs'; import path from 'path'; import crypto from 'crypto';
const root = path.resolve(new URL('../', import.meta.url).pathname);
const files = [];
const walk = (dir, rel = '') => { for (const n of fs.readdirSync(path.join(root, dir)).sort()) { const r = path.posix.join(rel, n), full = path.join(root, dir, n); if (fs.statSync(full).isDirectory()) walk(path.join(dir, n), r); else files.push(path.posix.join(dir === '.' ? '' : dir.split(path.sep).join('/'), n)); } };
walk('js'); walk('css'); walk('data'); walk('icons');
const all = ['./', 'index.html', 'manifest.webmanifest', ...files];
const hash = crypto.createHash('sha1'); for (const f of all) if (f !== './') hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 10);
const sw = `// Generated by tools/make-sw.mjs. Do not edit by hand.
const CACHE = 'tropical-merge-${version}';
const FILES = ${JSON.stringify(all, null, 1)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('tropical-merge-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); } return res; }).catch(() => req.mode === 'navigate' ? caches.match('index.html') : Response.error())));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js written: ${all.length} files, cache ${version}`);
