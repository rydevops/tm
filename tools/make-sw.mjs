// Generates the files that keep an installed copy in step with the deployed one. Run after any change: node tools/make-sw.mjs
//   sw.js          network-first service worker with an offline fallback cache, named after the build id
//   js/version.js  VERSION (package.json) + BUILD (content hash) + BUILT (when the hash last changed): shown in game
//   version.json   the same, fetched with no-store by a running game to learn whether a newer build is deployed
import fs from 'fs'; import path from 'path'; import crypto from 'crypto';
const root = path.resolve(new URL('../', import.meta.url).pathname);
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const versionJs = path.join(root, 'js/version.js');
if (!fs.existsSync(versionJs)) fs.writeFileSync(versionJs, "export const VERSION = '';\nexport const BUILD = '';\nexport const BUILT = '';\n");

const files = [];
const walk = (dir, rel = '') => { for (const n of fs.readdirSync(path.join(root, dir)).sort()) { const r = path.posix.join(rel, n), full = path.join(root, dir, n); if (fs.statSync(full).isDirectory()) walk(path.join(dir, n), r); else files.push(path.posix.join(dir === '.' ? '' : dir.split(path.sep).join('/'), n)); } };
walk('js'); walk('css'); walk('data'); walk('icons');
const all = ['./', 'index.html', 'manifest.webmanifest', ...files];

// The build id is a content hash of every shipped file plus the package version. js/version.js is left out because it holds the result.
const hash = crypto.createHash('sha1').update('v' + pkg.version);
for (const f of all) if (f !== './' && f !== 'js/version.js') hash.update(f).update(fs.readFileSync(path.join(root, f)));
const build = hash.digest('hex').slice(0, 10);

const old = /BUILD = '([0-9a-f]*)'.*?BUILT = '([^']*)'/s.exec(fs.readFileSync(versionJs, 'utf8'));
const built = old && old[1] === build && old[2] ? old[2] : new Date().toISOString().slice(0, 19) + 'Z';
fs.writeFileSync(versionJs, `// Generated by tools/make-sw.mjs. Do not edit by hand.\nexport const VERSION = '${pkg.version}';\nexport const BUILD = '${build}';\nexport const BUILT = '${built}';\n`);
fs.writeFileSync(path.join(root, 'version.json'), JSON.stringify({ version: pkg.version, build, built, files: all.filter(f => f !== './') }) + '\n');

const sw = `// Generated by tools/make-sw.mjs. Do not edit by hand.
// Network-first: online, every file is revalidated with the server, so a new deploy is picked up straight away and nothing can get stuck in a cache.
// The cache below only exists so the game still starts offline.
const CACHE = 'tropical-merge-${build}';
const FILES = ${JSON.stringify(all, null, 1)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('tropical-merge-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET') return;
  const url = new URL(req.url); if (url.origin !== location.origin || url.pathname.endsWith('/version.json')) return;
  e.respondWith(fetch(req.url, { cache: 'no-cache' }).then(res => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); } return res; }).catch(() => caches.match(req, { ignoreSearch: true }).then(hit => hit || (req.mode === 'navigate' ? caches.match('index.html') : Response.error()))));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js written: ${all.length} files, build ${build} (v${pkg.version})`);
